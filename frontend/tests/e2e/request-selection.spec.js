import { test, expect, setupAuthenticatedSession } from './fixtures/test-base.js';

for (const width of [1440, 375]) {
  test(`pickers dismiss naturally and show selected suppliers only at ${width}px`, async ({ page }) => {
    await page.setViewportSize({width,height:1000});
    await setupAuthenticatedSession(page,'admin'); await page.goto('/'); await page.locator('.sidebar-create').click();
    const categories=page.getByRole('button',{name:'Choose supplier categories'});
    await categories.click(); await expect(page.getByPlaceholder('Search categories...')).toBeVisible();
    await page.getByLabel('Product Name *',{exact:true}).click();
    await expect(page.getByPlaceholder('Search categories...')).not.toBeVisible();
    await categories.click(); await page.getByText('Tools',{exact:true}).click();
    await expect(page.getByRole('checkbox',{name:'Tools',exact:true})).toBeChecked();
    await page.keyboard.press('Escape');
    await expect(categories).toBeFocused(); await expect(categories).toHaveAttribute('aria-expanded','false');
    await page.locator('select').first().selectOption('selected');
    const picker=page.getByRole('region',{name:'Choose suppliers'});
    await expect(picker).toBeVisible();
    await picker.getByText('Al Noor Hardware & Tools',{exact:true}).click();
    await expect(picker.getByRole('checkbox',{name:/Al Noor Hardware/})).toBeChecked();
    await picker.getByRole('button',{name:'Done'}).click();
    await expect(picker).not.toBeVisible();
    await expect(page.locator('.selected-recipients')).toContainText('Al Noor Hardware');
    await expect(page.locator('.recipient-option')).toHaveCount(0);
    await page.getByRole('button',{name:'Change suppliers (1)'}).click();
    await expect(picker.getByRole('checkbox',{name:/Al Noor Hardware/})).toBeChecked();
    await page.getByLabel('Product Name *',{exact:true}).click();
    await expect(picker).not.toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  });
  test(`bulk review applies values to selected rows and uploads only those rows at ${width}px`, async ({ page }) => {
    await page.setViewportSize({width,height:1000});
    await setupAuthenticatedSession(page,'admin'); await page.goto('/'); await page.locator('.sidebar-create').click();
    await page.getByRole('button',{name:'Upload Material Requisition'}).click();
    await page.locator('#bulk-rfq-input').setInputFiles({name:'review.csv',mimeType:'text/csv',buffer:Buffer.from('Description,Qty,Last Cost\nExcluded copper pipe,10,5\nLong ceiling fan product name that must remain readable at every screen size,5,80\n')});
    const rows=page.locator('.bulk-item'); await expect(rows).toHaveCount(2);
    await rows.first().getByRole('checkbox').uncheck();
    await page.getByLabel('Default category',{exact:true}).selectOption('Electrical');
    await page.getByLabel('Default deadline (hours)',{exact:true}).fill('6');
    await page.getByRole('button',{name:'Apply category',exact:true}).click();
    await page.getByRole('button',{name:'Apply deadline',exact:true}).click();
    await expect(rows.first().getByLabel('Category',{exact:true})).toHaveValue('Hardware');
    await expect(rows.nth(1).getByLabel('Category',{exact:true})).toHaveValue('Electrical');
    await expect(rows.nth(1).getByLabel('Reply within (hours)',{exact:true})).toHaveValue('6');
    await page.getByRole('button',{name:'Clear selection'}).click();
    await expect(page.getByRole('button',{name:'Create 0 requests'})).toBeDisabled();
    await page.getByRole('button',{name:'Select all',exact:true}).click();
    await expect(rows.first().getByRole('checkbox')).toBeChecked();
    await rows.first().getByRole('checkbox').uncheck();
    await rows.nth(1).getByLabel('Maximum price (AED)',{exact:true}).fill('100');
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await page.screenshot({path:`/private/tmp/amafah-bulk-redesign-${width}.png`,fullPage:true});
    const request=page.waitForRequest(req=>req.url().includes('/rfq/bulk-create')&&req.method()==='POST');
    await page.getByRole('button',{name:'Create 1 request'}).click();
    const req=await request;
    const data=await new Response(req.postDataBuffer(),{headers:{'Content-Type':req.headers()['content-type']}}).formData();
    const csv=await data.get('file').text();
    expect(csv).not.toContain('Excluded copper pipe'); expect(csv).toContain('Long ceiling fan');
    const updates=JSON.parse(data.get('row_updates'));expect(updates).toHaveLength(1);
    expect(updates[0]).toMatchObject({category:'Electrical',deadline_hours:6,acceptable_price_max:100});
    await expect(page.getByRole('heading',{name:'Bulk RFQs Created'})).toBeVisible();
  });
}

test('large bulk review keeps independent shared changes and edits across pages', async ({page}) => {
  await page.setViewportSize({width:1440,height:1000});
  await setupAuthenticatedSession(page,'admin'); await page.goto('/'); await page.locator('.sidebar-create').click();
  await page.getByRole('button',{name:'Upload Material Requisition'}).click();
  const csv='Description,Qty\n'+Array.from({length:45},(_,i)=>`Item ${String(i+1).padStart(3,'0')},10`).join('\n');
  await page.locator('#bulk-rfq-input').setInputFiles({name:'large-review.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  const rows=page.locator('.bulk-item'); await expect(rows).toHaveCount(20);
  await expect(page.getByLabel('Default category',{exact:true})).toHaveValue('');
  await page.getByLabel('Default deadline (hours)',{exact:true}).fill('6');
  await page.getByRole('button',{name:'Apply deadline',exact:true}).click();
  await expect(rows.first().getByLabel('Category',{exact:true})).toHaveValue('Hardware');
  await expect(rows.first().getByLabel('Reply within (hours)',{exact:true})).toHaveValue('6');
  await page.getByLabel('Default category',{exact:true}).selectOption('Electrical');
  await page.getByLabel('Default deadline (hours)',{exact:true}).fill('');
  await page.getByRole('button',{name:'Apply category',exact:true}).click();
  await expect(rows.first().getByLabel('Reply within (hours)',{exact:true})).toHaveValue('6');
  await expect(rows.first().getByLabel('Category',{exact:true})).toHaveValue('Electrical');
  await page.getByLabel('Default category',{exact:true}).selectOption('');
  await expect(page.getByRole('button',{name:'Apply category',exact:true})).toBeDisabled();
  await rows.first().getByLabel('Target price (AED)',{exact:true}).fill('25');
  expect((await rows.first().boundingBox()).height).toBeLessThan(170);
  await page.getByRole('button',{name:'Next items',exact:true}).click();
  await expect(rows.first().locator('.bulk-product-title')).toHaveText('Item 021');
  await expect(rows.first().getByLabel('Reply within (hours)',{exact:true})).toHaveValue('6');
  await page.getByLabel('Find an item',{exact:true}).fill('Item 001');
  await expect(rows).toHaveCount(1);
  await expect(rows.first().getByLabel('Target price (AED)',{exact:true})).toHaveValue('25');
  await rows.first().getByRole('button',{name:'Details',exact:true}).click();
  await expect(rows.first().getByLabel('Product name',{exact:true})).toBeVisible();
  await page.getByLabel('Find an item',{exact:true}).fill('');
  await page.getByRole('button',{name:'Expand all details',exact:true}).click();
  await expect(rows.last().getByLabel('Product name',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Collapse all details',exact:true}).click();
  await expect(rows.first().getByLabel('Product name',{exact:true})).not.toBeVisible();
  const arrow=await rows.first().getByLabel('Category',{exact:true}).evaluate(el=>({appearance:getComputedStyle(el).appearance,position:getComputedStyle(el).backgroundPosition,padding:parseFloat(getComputedStyle(el).paddingRight)}));
  expect(arrow.appearance).toBe('none'); expect(arrow.position).toContain('14px'); expect(arrow.padding).toBeGreaterThanOrEqual(42);
  await page.screenshot({path:'/private/tmp/amafah-bulk-compact-large.png',fullPage:true});
});
